
public class AverageCalculator {
    public static void main(String[] args) {
        int score1 = 88;
        int score2 = 92;
        int score3 = 79;
        int score4 = 95;
        int score5 = 83;

        int sum = score1 + score2 + score3 + score4 + score5;
        double average = sum / 5.0;

        System.out.println("Average: " + average);
    }
}
